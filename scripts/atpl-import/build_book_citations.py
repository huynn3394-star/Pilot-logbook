"""Build additive book excerpts; never repackage a published question/progress identity."""
from pathlib import Path
import json,hashlib,sys,re
ROOT=Path(__file__).resolve().parents[2];D=ROOT/'data/atpl-additions'
def main():
 data=json.loads((D/'book-sources.json').read_text());mapping=json.loads((D/'question-book-sources.json').read_text());questions=json.loads((D/'source-questions.json').read_text());uids={q['uid'] for bank in questions.values() for q in bank}
 assert set(mapping)==uids,'Incomplete or foreign question citation map'
 for uid,refs in mapping.items():
  assert refs and len(refs)==len(set(refs)),uid
  for key in refs:assert key in data['citations'],(uid,key)
  assert data['books'][data['citations'][refs[0]]['book']]['role']=='primary',uid
 for key,c in data['citations'].items():
  book=data['books'][c['book']];assert 1<=c['pdfPage']<=book['pdfPages'],key
  assert c['printedPage'] and c['section'] and c['summaryVi'] and c['scope'] in ['principle','chart-method','manual-guidance'],key
  assert len(c['quote'].split())<=25,key
  assert re.fullmatch('[a-f0-9]{64}',c['pageTextSHA256']),key
  if book.get('url'):assert book['url'].startswith('https://') and '#' not in book['url'],key
  else:assert book['providedByUser'] and book['sourceFile'],key
  if book['role']=='primary':assert book['providedByUser'] and c['chapter']>0 and c['quote'],key
 # Copyrighted manuals are limited to brief paraphrases and <=25 quoted words per document.
 for key,b in data['books'].items():
  if not b['publicDomain'] and not b.get('providedByUser'):assert sum(len(c['quote'].split()) for c in data['citations'].values() if c['book']==key)<=25,key
 payload=json.dumps(dict(books=data['books'],citations=data['citations'],questions=mapping),ensure_ascii=False,separators=(',',':'))
 version=hashlib.sha256(payload.encode()).hexdigest()
 out='// Generated by scripts/atpl-import/build_book_citations.py. Progress identities are unchanged.\n'
 out+='export const BOOK_CITATIONS_VERSION='+json.dumps(version)+';\nconst DATA='+payload+';\n'
 out+='export function citationsFor(uid){return (DATA.questions[uid]||[]).map(id=>{const c=DATA.citations[id],b=DATA.books[c.book];return {id,...b,...c,url:b.url?b.url+"#page="+c.pdfPage:null};});}\n'
 (ROOT/'public/atpl/book-citations.js').write_text(out)
 print('Built',len(mapping),'question mappings;',len(data['citations']),'page references; version',version[:12])
if __name__=='__main__':main()
